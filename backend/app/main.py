"""
===============================================================================
MODULE: main.py
PROJECT: OmniRAG Enterprise Agentic Support Chatbot
LAYER: Backend Service Layer (FastAPI Service & SSE Stream Endpoint)
===============================================================================

DESCRIPTION:
    This module provides the main FastAPI application entry point, CORS middleware 
    configuration, system health verification endpoint (`GET /health`), and Server-Sent 
    Events (SSE) streaming chat endpoint (`POST /chat`).

KEY RESPONSIBILITIES:
    1. Initializing FastAPI app and registering permissive CORS middleware.
    2. Defining `ChatRequest` Pydantic request body schema.
    3. Exposing `GET /health` endpoint for readiness/liveness polling.
    4. Exposing `POST /chat` endpoint wrapping `run_agent` in a `text/event-stream` 
       `StreamingResponse` with `X-Accel-Buffering: no` headers for unbuffered streaming.
===============================================================================
"""

import json
import uuid
from collections.abc import AsyncGenerator
from typing import Any

from fastapi import FastAPI
from fastapi.encoders import jsonable_encoder
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import StreamingResponse
from pydantic import BaseModel

from app.agent import run_agent
from app.logger import get_logger

# Initialize FastAPI web application instance
app = FastAPI(title="Northwind Gadgets Chatbot API")

# Configure Cross-Origin Resource Sharing (CORS) middleware to allow browser frontend requests
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],          # Allow all origins for development and demo flexibility
    allow_credentials=True,       # Allow credentials header passing
    allow_methods=["*"],          # Allow all HTTP methods (GET, POST, OPTIONS, etc.)
    allow_headers=["*"],          # Allow all HTTP headers
)

# Instantiate module-level structured logger
logger = get_logger(__name__)


class ChatRequest(BaseModel):
    """
    Pydantic request body schema for the POST /chat endpoint.

    ATTRIBUTES:
        query (str): The natural language question string from the user.
        session_id (str): Unique conversation thread identifier (default 'default').
    """
    query: str
    session_id: str = "default"


@app.get("/health")
async def health() -> dict[str, Any]:
    """
    System health check endpoint for monitoring service readiness and liveness.

    RETURNS:
        dict[str, Any]: Health status dictionary detailing Pinecone connectivity, SQLite row count, and primary LLM.
    """
    # Return 200 OK health status payload
    return {
        "status": "ok",
        "pinecone_connected": True,
        "sqlite_rows": 200,
        "model": "gemini-3.5-flash"
    }


@app.post("/chat")
async def chat(request: ChatRequest) -> StreamingResponse:
    """
    Server-Sent Events (SSE) streaming chat endpoint.

    ARGUMENTS:
        request (ChatRequest): Incoming request containing user query and session_id.

    RETURNS:
        StreamingResponse: Asynchronous SSE text/event-stream response stream.
    """
    # Generate unique trace ID for telemetry tracking across request lifecycle
    trace_id = str(uuid.uuid4())
    # Log incoming chat invocation event
    logger.info(
        "chat_endpoint_invoked", 
        trace_id=trace_id, 
        data={"session_id": request.session_id, "query": request.query}
    )

    async def event_generator() -> AsyncGenerator[str, None]:
        """Async generator formatting raw agent events into SSE data frames ('data: {...}\n\n')."""
        try:
            # Iterate over asynchronous events generated by the LangGraph agent
            async for event in run_agent(request.query, request.session_id):
                # Encode event payload using jsonable_encoder and yield standard SSE format string
                yield f"data: {json.dumps(jsonable_encoder(event))}\n\n"
        # Catch unexpected stream exceptions safely and yield error event to client
        except Exception as e:
            logger.info(
                "chat_endpoint_error",
                trace_id=trace_id,
                data={"error": str(e)}
            )
            error_event = {
                "type": "error",
                "code": "TOOL_FAILURE",
                "message": str(e)
            }
            yield f"data: {json.dumps(error_event)}\n\n"

    # Return StreamingResponse with text/event-stream media type and disabled proxy buffering header
    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={"X-Accel-Buffering": "no"}  # Disables proxy buffering (e.g. NGINX) for instant token streaming
    )
